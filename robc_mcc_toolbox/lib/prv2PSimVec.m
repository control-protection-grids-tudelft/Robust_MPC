function Pvec = prv2PSimVec(prv,A,B,MMC_ONSHORE)
nra = size(A,1)*size(A,2);
nrb = size(B,1)*size(B,2);
NModel = size(prv,2);

Pvec = zeros(nra+nrb,NModel+1);

[Ac0_on, Bc0_on, Cc0_on] = getPlantModel(MMC_ONSHORE.Rr,...
                                            MMC_ONSHORE.Rac, ...
                                            MMC_ONSHORE.Lr,...
                                            MMC_ONSHORE.Lac, ...
                                            MMC_ONSHORE.w,...
                                            'OCC');

for i=1:NModel    

    [Ac_on, Bc_on, Cc_on] = getPlantModel(MMC_ONSHORE.Rr+prv(1,i),...
                                            MMC_ONSHORE.Rac+prv(2,i), ...
                                            MMC_ONSHORE.Lr+prv(3,i),...
                                            MMC_ONSHORE.Lac+prv(4,i), ...
                                            MMC_ONSHORE.w+prv(5,i),...
                                            'OCC');

    % Open-loop
    SYS_On_DISC = c2d(ss(Ac_on, Bc_on, Cc_on,[]),...
                                MMC_ONSHORE.Ts_pu,'zoh');
    SYS_On_Nom_DISC = c2d(ss(Ac0_on, Bc0_on, Cc0_on,[]),...
                                MMC_ONSHORE.Ts_pu,'zoh');

     % Delta continous-time parameters
    PAVec =  SYS_On_DISC.A - SYS_On_Nom_DISC.A;
    PBVec =  SYS_On_DISC.B - SYS_On_Nom_DISC.B;

    Pvec(:,i+1) = [reshape(PAVec',1,nra), reshape(PBVec',1,nrb)]';

end

end