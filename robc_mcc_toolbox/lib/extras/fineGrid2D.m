function [P, C1, C2] = fineGrid2D(cmin, cmax, n)
%FINEGRID2D  Fine rectangular grid over two coefficients.
%
%   P = FINEGRID2D(CMIN, CMAX, N) builds an evenly spaced grid over
%   [CMIN(1),CMAX(1)] x [CMIN(2),CMAX(2)] and returns its points as the
%   columns of a 2-by-M matrix P, with M = N(1)*N(2).
%
%   Inputs
%     CMIN  2-by-1 vector of lower bounds for the two coefficients
%     CMAX  2-by-1 vector of upper bounds (CMAX >= CMIN element-wise)
%     N     number of points per coefficient: a scalar (same for both)
%           or a 2-element vector [N1; N2], integers >= 2. Default: 100.
%
%   Outputs
%     P       2-by-M matrix; column k is one grid point [c1; c2].
%             Coefficient 1 varies fastest.
%     C1, C2  N1-by-N2 grid matrices (as from NDGRID), useful for
%             SURF/CONTOUR after you evaluate something on P:
%                Z = reshape(f(P), size(C1));
%                surf(C1, C2, Z)
%
%   Example
%     P = fineGrid2D([0; -1], [1; 1], [5; 3]);   % 2-by-15 grid
%     plot(P(1,:), P(2,:), '.')
% ---------------------------------------------------------------------- %
%  Note: This code has been generated by  AI Agent Claude
% ---------------------------------------------------------------------- %
    % --- Defaults and input checks -------------------------------------
    if nargin < 3 || isempty(n)
        n = 100;
    end
    if numel(cmin) ~= 2 || numel(cmax) ~= 2
        error('fineGrid2D:size', 'CMIN and CMAX must each have 2 elements.');
    end
    cmin = cmin(:);   % force column vectors
    cmax = cmax(:);
    if any(cmin > cmax)
        error('fineGrid2D:bounds', ...
              'Each element of CMIN must be <= the corresponding element of CMAX.');
    end
    if isscalar(n)
        n = [n; n];
    end
    n = n(:);
    if numel(n) ~= 2 || any(n < 2) || any(n ~= round(n))
        error('fineGrid2D:n', ...
              'N must be a scalar or 2-element vector of integers >= 2.');
    end

    % --- Grid along each coefficient ------------------------------------
    c1 = linspace(cmin(1), cmax(1), n(1));
    c2 = linspace(cmin(2), cmax(2), n(2));

    % --- Combine into all (c1, c2) pairs --------------------------------
    [C1, C2] = ndgrid(c1, c2);          % N1-by-N2 each
    P = [C1(:).'; C2(:).'];             % 2-by-(N1*N2)
end
