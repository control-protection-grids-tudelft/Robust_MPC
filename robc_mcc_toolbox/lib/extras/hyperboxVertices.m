function V = hyperboxVertices(xmin, xmax)
%HYPERBOXVERTICES  Vertices of an axis-aligned hyperbox.
%
%   V = HYPERBOXVERTICES(XMIN, XMAX) returns the 2^n vertices of the
%   n-dimensional box  [XMIN(1),XMAX(1)] x ... x [XMIN(n),XMAX(n)].
%
%   Inputs
%     XMIN  n-by-1 vector of lower bounds
%     XMAX  n-by-1 vector of upper bounds (XMAX >= XMIN element-wise)
%
%   Output
%     V     n-by-2^n matrix; each column is one vertex.
%
%   Vertex ordering: column k (k = 1..2^n) uses XMAX(i) in dimension i if
%   bit i of (k-1) is 1, and XMIN(i) otherwise. So the first column is
%   XMIN, the last column is XMAX, and dimension 1 alternates fastest.
%
%   Example
%     V = hyperboxVertices([0; 0; 0], [1; 2; 3])
%
%   Note: the number of vertices is 2^n, so memory use grows quickly
%   (n = 20 already gives over a million vertices).

% ---------------------------------------------------------------------- %
%  Note: This code has been generated by  AI Agent Claude
% ---------------------------------------------------------------------- %
    % --- Input checks ---------------------------------------------------
    if ~isvector(xmin) || ~isvector(xmax) || numel(xmin) ~= numel(xmax)
        error('hyperboxVertices:size', ...
              'XMIN and XMAX must be vectors of the same length.');
    end
    xmin = xmin(:);   % force column vectors
    xmax = xmax(:);
    if any(xmin > xmax)
        error('hyperboxVertices:bounds', ...
              'Each element of XMIN must be <= the corresponding element of XMAX.');
    end

    n = numel(xmin);
    N = 2^n;                                  % number of vertices

    % --- Binary pattern ---------------------------------------------------
    % B(i,k) is true when vertex k takes the upper bound in dimension i.
    k = 0:N-1;                                % 1-by-N vertex indices
    p = 2.^(0:n-1).';                         % n-by-1 bit weights
    B = logical(mod(floor(k ./ p), 2));       % n-by-N (implicit expansion)

    % --- Build vertices by selection (exact, no rounding) -----------------
    V    = repmat(xmin, 1, N);
    Xmax = repmat(xmax, 1, N);
    V(B) = Xmax(B);
end
